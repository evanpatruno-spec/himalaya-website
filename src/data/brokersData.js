export const loadStoredBrokers = () => {
  try {
    if (typeof localStorage !== 'undefined') {
      const raw = localStorage.getItem('himalaya_broker_accounts');
      if (raw) {
        const parsed = JSON.parse(raw);
        if (Array.isArray(parsed) && parsed.length > 0) {
          return parsed;
        }
      }
    }
  } catch (e) {
    console.error('Error loading stored brokers:', e);
  }
  return INITIAL_HIMALAYA_BROKERS;
};

export const saveStoredBrokers = (brokers) => {
  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('himalaya_broker_accounts', JSON.stringify(brokers));
    }
  } catch (e) {
    console.error('Error saving brokers:', e);
  }
};

// 🛡️ VÉRIFICATION DES DROITS ET CONFIDENTIALITÉ OACIQ

// Direction d'Agence, Présidence et Administration (Directeur d'agence agréé DA, Président, Admin)
export const isAgencyDirector = (brokerName = '') => {
  const bLower = String(brokerName || '').toLowerCase().trim();
  return bLower.includes('direction') || 
         bLower.includes('directeur') ||
         bLower.includes('président') ||
         bLower.includes('president') ||
         bLower.includes('fondateur') ||
         bLower.includes('admin');
};

// Seuls les courtiers assignés aux mandats gagnés ou la direction peuvent modifier un mandat
export const canEditMandate = (currentUser = '', prospect = {}) => {
  if (!prospect) return true;
  if (isAgencyDirector(currentUser)) return true;
  
  const userLower = String(currentUser || '').toLowerCase().trim();
  const userFirst = userLower.split(' ')[0] || '';
  const resolvedUser = resolveBrokerFullName(currentUser).toLowerCase().trim();
  
  const assigned = String(prospect.assigned_broker || prospect.author || '').toLowerCase().trim();
  
  let coBrokers = [];
  // 1. Depuis prospect.co_brokers directement
  if (Array.isArray(prospect.co_brokers)) {
    prospect.co_brokers.forEach(c => {
      const val = typeof c === 'string' ? c : (c?.name || '');
      if (val) coBrokers.push(String(val).toLowerCase().trim());
    });
  }
  // 2. Depuis prospect.extra_features
  try {
    const extra = typeof prospect.extra_features === 'string' ? JSON.parse(prospect.extra_features) : (prospect.extra_features || {});
    if (Array.isArray(extra.co_brokers)) {
      extra.co_brokers.forEach(c => {
        const val = typeof c === 'string' ? c : (c?.name || '');
        if (val) coBrokers.push(String(val).toLowerCase().trim());
      });
    }
    if (Array.isArray(extra.brokers_details)) {
      extra.brokers_details.forEach(b => {
        if (b && b.name) coBrokers.push(String(b.name).toLowerCase().trim());
      });
    }
  } catch(e) {}

  const isAssigned = (userLower && assigned.includes(userLower)) || 
                     (resolvedUser && assigned.includes(resolvedUser)) ||
                     (userFirst && userFirst.length >= 3 && assigned.includes(userFirst)) || 
                     coBrokers.some(c => (userLower && c.includes(userLower)) || (resolvedUser && c.includes(resolvedUser)) || (userFirst && userFirst.length >= 3 && c.includes(userFirst)));

  // Si c'est un mandat sous contrat actif (Mandat Gagné, Notarié, Promesse d'Achat)
  const isWon = (prospect.status || '').toLowerCase().includes('gagné') || 
                (prospect.status || '').toLowerCase().includes('notarié') ||
                (prospect.status || '').toLowerCase().includes('promesse') ||
                (prospect.status || '').toLowerCase().includes('fermé');
  
  // Si c'est un mandat gagné officiel : restriction stricte aux assignés + direction
  if (isWon) {
    return isAssigned;
  }

  // Pour la prospection brute non encore signée
  if (!prospect.assigned_broker || assigned === 'non assigné' || assigned === 'équipe himalaya') {
    return true; // Prospection ouverte
  }

  return isAssigned;
};

// 🔍 Résout le nom complet officiel d'un courtier à partir d'un courriel, identifiant ou fragment
export const resolveBrokerFullName = (identifier = '') => {
  if (!identifier) return '';
  const clean = String(identifier).trim().toLowerCase();
  const brokers = loadStoredBrokers();
  
  // 1. Match exact par nom
  const byName = brokers.find(b => b.name.toLowerCase() === clean);
  if (byName) return byName.name;

  // 2. Match exact par email
  const byEmail = brokers.find(b => b.email && b.email.toLowerCase() === clean);
  if (byEmail) return byEmail.name;

  // 3. Match exact par id
  const byId = brokers.find(b => b.id.toLowerCase() === clean);
  if (byId) return byId.name;

  // 4. Match par email partiel
  const byEmailPart = brokers.find(b => {
    const emailPrefix = (b.email || '').split('@')[0].toLowerCase();
    return clean.includes(emailPrefix) || emailPrefix.includes(clean);
  });
  if (byEmailPart) return byEmailPart.name;

  // 5. Match par prénom
  const firstWord = clean.split(/[@._\s]/)[0];
  if (firstWord && firstWord.length >= 3) {
    const byFirst = brokers.find(b => b.name.toLowerCase().startsWith(firstWord));
    if (byFirst) return byFirst.name;
  }

  return identifier;
};

