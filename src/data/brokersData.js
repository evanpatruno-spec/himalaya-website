export const maskContactName = (prenom = '', nom = '', organisation = '') => {
  const p = (prenom || '').trim();
  const n = (nom || '').trim();
  const initialP = p ? p[0] + '.' : '';
  const initialN = n ? n[0] + '.' : '';
  
  if (organisation && organisation.trim()) {
    return `${initialP} ${initialN} (${organisation.trim()})`;
  }
  return `${initialP} ${initialN}`.trim() || 'Contact';
};


