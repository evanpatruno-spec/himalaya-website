// 🔒 CONFIDENTIALITÉ DES CONTACTS CRM (ACQUÉREURS & VENDEURS)
// Chaque courtier protège son portefeuille de clients : coordonnées directes masquées pour les autres
// tout en maintenant les critères de recherche 100% visibles pour le matching d'équipe !
export const canViewContactDetails = (currentUser = '', contact = {}, simulatedRole = 'real') => {
  if (!contact) return true;
  
  // Si le mode de simulation d'un autre courtier est activé (pour la démo en agence)
  if (simulatedRole === 'other_broker') {
    const assigned = String(contact.assigned_broker || contact.created_by || '').toLowerCase().trim();
    // Seuls les contacts explicitement publics de l'agence restent ouverts
    if (assigned === 'équipe himalaya' || assigned === 'tous' || assigned === 'public') {
      return true;
    }
    return false;
  }

  // Si aucun courtier n'est assigné ou équipe générale -> ouvert
  const assigned = String(contact.assigned_broker || contact.created_by || '').toLowerCase().trim();
  if (!assigned || assigned === 'non assigné' || assigned === 'équipe himalaya' || assigned === 'tous') {
    return true;
  }

  const userLower = String(currentUser || '').toLowerCase().trim();
  const userFirst = userLower.split(' ')[0] || '';

  // 1. Si l'utilisateur connecté est le courtier assigné au contact
  if (userLower && (assigned.includes(userLower) || userLower.includes(assigned) || (userFirst && assigned.includes(userFirst)))) {
    return true;
  }

  // 2. La Direction d'Agence (Roger Rhéaume, Direction, DA) a un droit de supervision déontologique
  if (isAgencyDirector(currentUser)) {
    return true;
  }

  return false;
};

export const canEditContact = (currentUser = '', contact = {}, simulatedRole = 'real') => {
  return canViewContactDetails(currentUser, contact, simulatedRole);
};

